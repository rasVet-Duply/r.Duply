export function t(s: string | undefined | null): string {
  if (!s) return '';
  if (current === 'uz') return s;
  const e = D[s];
  return e ? e[current === 'en' ? 0 : 1] : s;
}

export const errMsg = (e: unknown, fallback: string) => t((e as { userFacingMessage?: string })?.userFacingMessage ?? fallback);

export const getLang = () => current;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: current, setLang: () => {} });

export function LangProvider({ children }: { children: (lang: Lang) => ReactNode }) {
  const [lang, setState] = useState<Lang>(current);
  const setLang = (l: Lang) => {
    current = l;
    localStorage.setItem(KEY, l);
    document.documentElement.lang = l;
    setState(l);
  };
  return <Ctx.Provider value={{ lang, setLang }}>{children(lang)}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
